[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $ReleaseDirectory,
    [Parameter(Mandatory)] [string] $DownloadDirectory
)

$ErrorActionPreference = 'Stop'
$ReleaseDirectory = (Resolve-Path -LiteralPath $ReleaseDirectory).ProviderPath
$DownloadDirectory = (Resolve-Path -LiteralPath $DownloadDirectory).ProviderPath
if ($ReleaseDirectory -eq $DownloadDirectory) {
    throw 'Download the GitHub assets into a separate directory.'
}

$LocalManifest = Join-Path $ReleaseDirectory 'SHA256SUMS.txt'
$ChecksumLine = (Get-Content -LiteralPath $LocalManifest -Raw).TrimEnd()
if ($ChecksumLine -cnotmatch '\A([a-f0-9]{64}) \*(ETS2-Configurable-Mirrors-v[0-9]+\.[0-9]+\.[0-9]+-windows-x64\.exe)\z') {
    throw 'The local SHA256SUMS.txt must contain exactly one Windows executable checksum.'
}
$ExpectedHash = $Matches[1]
$Exe = $Matches[2]
$LocalExe = Get-Item -LiteralPath (Join-Path $ReleaseDirectory $Exe)
$DownloadedExe = Get-Item -LiteralPath (Join-Path $DownloadDirectory $Exe)

$LocalHash = (Get-FileHash -LiteralPath $LocalExe.FullName -Algorithm SHA256).Hash
if ($LocalHash -ne $ExpectedHash) {
    throw 'The local executable does not match the checksum generated by release.ps1.'
}
if ($DownloadedExe.Length -ne $LocalExe.Length) {
    throw "Download size mismatch for $Exe. Expected $($LocalExe.Length) bytes, received $($DownloadedExe.Length)."
}
$DownloadedHash = (Get-FileHash -LiteralPath $DownloadedExe.FullName -Algorithm SHA256).Hash
if ($DownloadedHash -ne $ExpectedHash) {
    throw "Download SHA-256 mismatch for $Exe. Expected $ExpectedHash, received $DownloadedHash."
}

$DownloadedManifest = Join-Path $DownloadDirectory 'SHA256SUMS.txt'
$LocalManifestHash = (Get-FileHash -LiteralPath $LocalManifest -Algorithm SHA256).Hash
$DownloadedManifestHash = (Get-FileHash -LiteralPath $DownloadedManifest -Algorithm SHA256).Hash
if ($DownloadedManifestHash -ne $LocalManifestHash) {
    throw 'The downloaded SHA256SUMS.txt differs from the local release manifest.'
}

Write-Host "Verified $Exe ($($LocalExe.Length) bytes, SHA-256 $ExpectedHash) and SHA256SUMS.txt."
